// Calculate bounding box for any SVG path
export function calculatePathBounds(pathData: string): StateBounds {
  // Simple regex to extract coordinates from SVG path
  const coords = pathData.match(/[\d.]+/g)?.map(Number) || []
  
  if (coords.length < 2) {
    return { minX: 0, minY: 0, maxX: 100, maxY: 100, width: 100, height: 100 }
  }
  
  const xCoords = coords.filter((_, i) => i % 2 === 0)
  const yCoords = coords.filter((_, i) => i % 2 === 1)
  
  const minX = Math.min(...xCoords)
  const maxX = Math.max(...xCoords)
  const minY = Math.min(...yCoords)
  const maxY = Math.max(...yCoords)
  
  return {
    minX,
    minY,
    maxX,
    maxY,
    width: maxX - minX,
    height: maxY - minY
  }
}

// Generate optimized viewBox for a state with padding
export function generateOptimalViewBox(stateId: string, padding: number = 20): string {
  const pathData = ACCURATE_STATE_PATHS[stateId]
  if (!pathData) return '0 0 400 300'
  
  const bounds = calculatePathBounds(pathData)
  
  return `${bounds.minX - padding} ${bounds.minY - padding} ${bounds.width + (padding * 2)} ${bounds.height + (padding * 2)}`
}

